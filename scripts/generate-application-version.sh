#!/usr/bin/env bash
#
# Generates the application-level version (as opposed to the backend's or
# frontend's own package version) and writes it as a variable into both the
# backend and frontend source trees.
#
# Resolution order:
#   1. If HEAD is checked out exactly on a tag (e.g. a release build), that
#      tag is used.
#   2. Otherwise, the latest tag in the repository (highest semantic
#      version) is used.
#
# If the version cannot be resolved (not a git repository, no tags, git
# missing, ...) or either output file fails to write, a placeholder version
# is written to both files instead, so downstream builds are not blocked by
# this script.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

BACKEND_VERSION_FILE="${REPO_ROOT}/backend/src/keychain/application_version.py"
FRONTEND_VERSION_FILE="${REPO_ROOT}/frontend/src/utils/application-version.json"

PLACEHOLDER_VERSION="0.0.0"

resolve_version() {
  local current_tag latest_tag

  if current_tag="$(git -C "${REPO_ROOT}" describe --tags --exact-match 2>/dev/null)"; then
    echo "${current_tag}"
    return 0
  fi

  latest_tag="$(git -C "${REPO_ROOT}" tag --list --sort=-version:refname | head -n 1)"
  if [[ -z "${latest_tag}" ]]; then
    return 1
  fi

  echo "${latest_tag}"
}

write_backend() {
  cat > "${BACKEND_VERSION_FILE}" <<EOF
"""Generated application-level version.

This file is generated by scripts/generate-application-version.sh.
Do not edit it manually; changes will be overwritten.
"""

__all__ = ["APPLICATION_VERSION"]

APPLICATION_VERSION = "$1"
EOF
}

write_frontend() {
  cat > "${FRONTEND_VERSION_FILE}" <<EOF
{
  "version": "$1"
}
EOF
}

if VERSION="$(resolve_version)"; then
  echo "Resolved application version: ${VERSION}"
else
  VERSION="${PLACEHOLDER_VERSION}"
  echo "Could not resolve application version from git tags, using placeholder: ${VERSION}" >&2
fi

if write_backend "${VERSION}" && write_frontend "${VERSION}"; then
  echo "Application version written: ${VERSION}"
else
  echo "Failed to write application version files, falling back to placeholder" >&2
  write_backend "${PLACEHOLDER_VERSION}"
  write_frontend "${PLACEHOLDER_VERSION}"
  exit 1
fi
